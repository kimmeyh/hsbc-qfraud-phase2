"""The test inventory covers every test file (F180, Sprint 31 Task B).

`docs/testing/F180_TEST_INVENTORY.md` is generated by
`scripts/test_inventory.py`. A test file that is not in it is a guard
nobody has costed or placed, so this fails until the inventory is
regenerated. The column rules are tested on hand-built rows.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INVENTORY = ROOT / "docs" / "testing" / "F180_TEST_INVENTORY.md"
SCRIPT = ROOT / "scripts" / "test_inventory.py"
THIS = Path(__file__).relative_to(ROOT).as_posix()
sys.path.insert(0, str(ROOT / "scripts"))

import test_inventory as inv  # noqa: E402


def _rows() -> set[str]:
    return {ln.split("|")[1].strip()
            for ln in INVENTORY.read_text(encoding="utf-8").splitlines()
            if ln.startswith("| test_")}


def test_every_test_file_is_in_the_inventory():
    files = {p.name for p in (ROOT / "experiments" / "src").glob("test_*.py")}
    missing = sorted(files - _rows())
    assert not missing, (
        f"{len(missing)} test file(s) not in {INVENTORY.name}: {missing}. "
        "Regenerate it: see scripts/test_inventory.py's docstring.")
    gone = sorted(_rows() - files)
    assert not gone, f"rows for test files that no longer exist: {gone}"


def test_the_place_and_tier_follow_the_rules():
    assert inv.runs_in({"tests": 3, "proofs": 1, "slow": 0}) == "push, full"
    assert inv.runs_in({"tests": 1, "proofs": 1, "slow": 0}) == "full"
    assert inv.runs_in({"tests": 2, "proofs": 0, "slow": 2}) == "local"
    assert inv.runs_in({"tests": 0, "proofs": 0, "slow": 0}) == "nowhere"
    assert inv.tier("test_evidence_immutability.py") == "high"
    assert inv.tier("test_device_store_required.py") == "high"
    assert inv.tier("test_agent_status.py") == "normal"


def test_quoted_docstrings_are_us_english(tmp_path):
    # The inventory quotes each file's docstring into a tracked markdown
    # file, which test_us_english scans (Sprint 31: one quote broke it).
    f = tmp_path / "test_x.py"
    f.write_bytes(('"""A ' + "sizea" + 'ble, ' + "Colo" + 'ur check."""\n')
                  .encode("utf-8"))
    assert inv.guards(f) == "A sizable, Color check."


def test_a_file_absent_from_a_report_is_blank_not_zero():
    """Sprint 31 Task N: a file no report holds was shown as 0.0 s local,
    which reads as measured."""
    rows = {"test_suite_times.py": {"tests": 3, "proofs": 1, "slow": 0}}
    absent = inv.render(rows, {}, {}, "l.xml", "c.xml")
    row = next(ln for ln in absent.splitlines()
               if ln.startswith("| test_suite_times.py"))
    assert [c.strip() for c in row.split("|")[7:11]] == ["", "", "", ""]
    held = inv.render(rows, {"test_suite_times.py": [1.25, 2.0]}, {},
                      "l.xml", "c.xml")
    row = next(ln for ln in held.splitlines()
               if ln.startswith("| test_suite_times.py"))
    assert [c.strip() for c in row.split("|")[7:9]] == ["1.2", "2.0"]


def test_the_inventory_can_fail():
    from injection import Mutation, assert_can_fail, run_pytest

    def test(name):
        return lambda: run_pytest(f"{THIS}::{name}", ROOT)
    assert_can_fail([Mutation(INVENTORY, "| test_agent_prompts.py |",
                              "| test_agent_promptz.py |",
                              expect_occurrences=1)],
                    test("test_every_test_file_is_in_the_inventory"),
                    "a test file missing from the inventory")
    assert_can_fail([Mutation(SCRIPT,
                              "    if row[\"tests\"] - row[\"slow\"] > 0:\n",
                              "    if row[\"tests\"] > 0:\n",
                              expect_occurrences=1)],
                    test("test_the_place_and_tier_follow_the_rules"),
                    "a slow-only file placed in the full job")
    assert_can_fail([Mutation(SCRIPT, "    \"test_device_store\", ",
                              "    ", expect_occurrences=1)],
                    test("test_the_place_and_tier_follow_the_rules"),
                    "the device store guard out of the high tier")
    assert_can_fail([Mutation(SCRIPT,
                              "    s = us_english(m.group(1) if m else first)\n",
                              "    s = (m.group(1) if m else first)\n",
                              expect_occurrences=1)],
                    test("test_quoted_docstrings_are_us_english"),
                    "a docstring quoted without the US English pairs")
    assert_can_fail([Mutation(SCRIPT,
                              "        lt, ct = local.get(name), ci.get(name)\n",
                              "        lt, ct = local.get(name, [0.0, 0.0]), "
                              "ci.get(name)\n",
                              expect_occurrences=1)],
                    test("test_a_file_absent_from_a_report_is_blank_not_zero"),
                    "an unmeasured file shown as 0.0 s")
